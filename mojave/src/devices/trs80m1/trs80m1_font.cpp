uint8_t textGlyphRow(uint8_t ch, uint8_t row) {
    // TRS-80 Model I stores text letters as 0x00-0x1F (@ and A-Z as 0x00 and
    // 0x01-0x1A); the character generator displays them with the same glyphs as
    // 0x40-0x5F. Fold them into the ASCII range the glyph table understands.
    if (ch <= 0x1F)
        ch = static_cast<uint8_t>(ch + 0x40);
    if (ch >= 96 && ch <= 122)
        ch = static_cast<uint8_t>(ch - 32);
    if (row >= kGlyphRows)
        return 0;
    return lookupGlyphRows(ch)[row] & 0x3F;
}

