const uint8_t* lookupGlyphRows(uint8_t ch) {
    if (ch == ' ')
        return kSpace;
    if (ch == '_')
        return kCursorBlock;
    if (ch == '@')
        return kGlyphAt;
    if (ch >= '!' && ch <= '/')
        return kSymbolsLow[ch - '!'];
    if (ch >= '0' && ch <= '9')
        return kDigits[ch - '0'];
    if (ch >= ':' && ch <= '?')
        return kSymbolsHigh[ch - ':'];
    if (ch >= 'A' && ch <= 'Z')
        return kLetters[ch - 'A'];
    return kBlank;
}

