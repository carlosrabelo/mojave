uint8_t textGlyphRow(uint8_t ch, uint8_t row) {
    // Model I/III software stores @ and A-Z as 0x00-0x1A; fold into ASCII.
    if (ch <= 0x1F)
        ch = static_cast<uint8_t>(ch + 0x40);
    if (row >= kGlyphRows)
        return 0;
    if (ch >= 'a' && ch <= 'z')
        return kLowerLetters[ch - 'a'][row];
    return narrowGlyphRow(ch, row);
}

