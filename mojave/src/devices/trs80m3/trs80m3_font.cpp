const uint8_t* lookupNarrowGlyphRows(uint8_t ch) {
    if (ch == ' ')
        return kSpace;
    if (ch == '_')
        return kCursorBlock;
    if (ch == '@')
        return kGlyphAt;
    if (ch >= '!' && ch <= '/')
        return kSymbolsLow[ch - '!'];
    if (ch >= '0' && ch <= '9')
        return kDigits[ch - '0'];
    if (ch >= ':' && ch <= '?')
        return kSymbolsHigh[ch - ':'];
    if (ch >= 'A' && ch <= 'Z')
        return kLetters[ch - 'A'];
    return kBlank;
}

// Returns a 6-bit narrow glyph row (bit 5 = left pixel), centered into the
// 8-dot Model III cell by shifting one bit left.
uint8_t narrowGlyphRow(uint8_t ch, uint8_t row) {
    if (ch <= 0x1F)
        ch = static_cast<uint8_t>(ch + 0x40);
    if (ch >= 96 && ch <= 122)
        ch = static_cast<uint8_t>(ch - 32);
    return static_cast<uint8_t>((lookupNarrowGlyphRows(ch)[row] & 0x3F) << 1) & 0xFE;
}

